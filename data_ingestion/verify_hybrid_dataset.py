import xarray as xr
import os
from pathlib import Path

def generate_manifest():
    print("==================================================")
    print("   OCEANEMBED DATASET MANIFEST & METADATA         ")
    print("==================================================\n")
    
    monthly_path = Path("../data/processed_0.25deg/monthly")
    daily_path = Path("../data/processed_0.25deg/daily")
    
    # Check Monthly Data
    print("[1] LONG-TERM CLIMATE MEMORY (Monthly Resolution)")
    if monthly_path.exists():
        files = list(monthly_path.glob("*.nc"))
        print(f"    -> Found {len(files)} NetCDF Files")
        print(f"    -> Temporal Coverage: 1997 to 2026 (30 Years)")
        print(f"    -> Variables: thetao (Temp), so (Salinity), zos (SSH), uo, vo")
        try:
            sample = xr.open_dataset(files[0])
            print(f"    -> Matrix Dimensions: {dict(sample.sizes)}")
            sample.close()
        except:
            pass
    else:
        print("    -> Data not found locally (Ignored for GitHub)")
        
    print("\n[2] HIGH-FREQUENCY DYNAMICS (Daily Resolution)")
    if daily_path.exists():
        files = list(daily_path.glob("*.nc"))
        print(f"    -> Found {len(files)} NetCDF Files")
        print(f"    -> Temporal Coverage: 2022 to 2026 (5 Years)")
        print(f"    -> Variables: thetao (Temp), so (Salinity), zos (SSH), uo, vo")
        try:
            sample = xr.open_dataset(files[0])
            print(f"    -> Matrix Dimensions: {dict(sample.sizes)}")
            sample.close()
        except:
            pass
    else:
        print("    -> Data not found locally (Ignored for GitHub)")
        
    print("\n==================================================")
    print("   AUTOMATED MANIFEST GENERATED BY PIPELINE       ")
    print("==================================================")

if __name__ == "__main__":
    generate_manifest()
